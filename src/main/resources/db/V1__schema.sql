-- =====================================================================
-- UCC Pasto 3D - Database schema (PostgreSQL)
-- This repository is the SINGLE source of truth for the data model.
-- =====================================================================

CREATE TABLE IF NOT EXISTS building (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(20)  NOT NULL UNIQUE,
    name            VARCHAR(120) NOT NULL,
    description     TEXT,
    pos_x           DOUBLE PRECISION NOT NULL DEFAULT 0,   -- position on the 3D map (meters)
    pos_z           DOUBLE PRECISION NOT NULL DEFAULT 0,
    width           DOUBLE PRECISION NOT NULL DEFAULT 10,
    depth           DOUBLE PRECISION NOT NULL DEFAULT 10,
    floors          INTEGER      NOT NULL DEFAULT 1,
    basements       INTEGER      NOT NULL DEFAULT 0,       -- underground floors
    color           VARCHAR(9)   NOT NULL DEFAULT '#cfd8dc',
    type            VARCHAR(30)  NOT NULL DEFAULT 'BUILDING' -- BUILDING, GREEN_AREA, PLAZA, ENTRANCE, BIKE_STATION
);

CREATE TABLE IF NOT EXISTS place (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(150) NOT NULL,
    type            VARCHAR(40)  NOT NULL,                  -- OFFICE, LABORATORY, CLASSROOM, SERVICE, CLINIC, FACULTY...
    building_id     INTEGER      NOT NULL REFERENCES building(id),
    floor           INTEGER      NOT NULL DEFAULT 1,        -- negative = basement (-1 = basement 1)
    description     TEXT,
    schedule        VARCHAR(150),
    phone           VARCHAR(60),
    email           VARCHAR(120)
);

CREATE TABLE IF NOT EXISTS program (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(150) NOT NULL,
    faculty             VARCHAR(150) NOT NULL,
    level               VARCHAR(30)  NOT NULL,              -- UNDERGRADUATE, SPECIALIZATION, MASTERS, TECHNICAL
    modality            VARCHAR(30)  NOT NULL DEFAULT 'IN_PERSON',
    duration_semesters  INTEGER,
    degree_title        VARCHAR(150),
    description         TEXT,
    building_id         INTEGER REFERENCES building(id)
);

CREATE TABLE IF NOT EXISTS faq (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category        VARCHAR(60)  NOT NULL,
    question        VARCHAR(300) NOT NULL,
    answer          TEXT         NOT NULL,
    keywords        VARCHAR(300)                            -- comma separated, they help the local assistant
);

CREATE TABLE IF NOT EXISTS conversation (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question        TEXT         NOT NULL,
    answer          TEXT         NOT NULL,
    provider        VARCHAR(40)  NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_place_building   ON place(building_id);
CREATE INDEX IF NOT EXISTS idx_program_building ON program(building_id);
