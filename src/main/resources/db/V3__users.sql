-- =====================================================================
-- UCC Pasto 3D - Users, sessions and conversations per user
--
-- Password security:
--   1. The browser NEVER sends the password: it sends its SHA-256 fingerprint.
--   2. The backend stores only a BCrypt hash of that fingerprint (with a random salt).
--   => The original password never travels over the network and is never stored.
-- =====================================================================

CREATE TABLE IF NOT EXISTS app_user (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(80)  NOT NULL,
    email           VARCHAR(120) NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,                      -- BCrypt( SHA-256(password) )
    role            VARCHAR(20)  NOT NULL DEFAULT 'STUDENT',    -- STUDENT, VISITOR, ADMIN
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login      TIMESTAMP
);

-- Every conversation with Coopi belongs to a user (NULL = guest)
ALTER TABLE conversation ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES app_user(id);
ALTER TABLE conversation ADD COLUMN IF NOT EXISTS action VARCHAR(40);

CREATE INDEX IF NOT EXISTS idx_conversation_user ON conversation(user_id);
