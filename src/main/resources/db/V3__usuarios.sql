-- =====================================================================
-- UCC Pasto 3D - Usuarios, sesiones y conversaciones por usuario
--
-- Seguridad de la contraseña:
--   1. El navegador NUNCA envía la contraseña: envía su huella SHA-256.
--   2. El backend guarda solo un hash BCrypt de esa huella (con sal aleatoria).
--   => La contraseña original no viaja por la red ni se guarda en la base de datos.
-- =====================================================================

CREATE TABLE IF NOT EXISTS usuario (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(80)  NOT NULL,
    correo          VARCHAR(120) NOT NULL UNIQUE,
    hash_clave      VARCHAR(100) NOT NULL,           -- BCrypt( SHA-256(contraseña) )
    rol             VARCHAR(20)  NOT NULL DEFAULT 'ESTUDIANTE', -- ESTUDIANTE, VISITANTE, ADMIN
    creado_en       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_ingreso  TIMESTAMP
);

-- Cada conversación con Coopi queda asociada al usuario (NULL = invitado)
ALTER TABLE conversacion ADD COLUMN IF NOT EXISTS usuario_id INTEGER REFERENCES usuario(id);
ALTER TABLE conversacion ADD COLUMN IF NOT EXISTS accion VARCHAR(40);

CREATE INDEX IF NOT EXISTS idx_conversacion_usuario ON conversacion(usuario_id);
